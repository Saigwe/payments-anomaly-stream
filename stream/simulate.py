"""Replay both days through the processor and score day 2 against the fraud labels.

Usage: python -m stream.simulate --data data/raw/creditcard.pq --out output
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import duckdb
import numpy as np
import pandas as pd

from .events import SECONDS_PER_DAY, delivery, load
from .processor import Processor
from .scoring import ALERT_BUDGET, train

BATCH = 500


def evaluate(day2: pd.DataFrame, flagged: set[int]) -> dict:
    f = day2["txn_id"].isin(flagged)
    fraud = day2["is_fraud"]
    tp = int((f & fraud).sum())
    return {"alerts": int(f.sum()), "frauds_caught": tp, "frauds": int(fraud.sum()),
            "precision": round(tp / max(int(f.sum()), 1), 4), "recall": round(tp / int(fraud.sum()), 4),
            "fraud_value_caught": round(float(day2.loc[f & fraud, "Amount"].sum()), 2),
            "fraud_value": round(float(day2.loc[fraud, "Amount"].sum()), 2),
            "alert_rate": round(float(f.mean()), 5)}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="data/raw/creditcard.pq")
    ap.add_argument("--out", type=Path, default=Path("output"))
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    tx = load(args.data)
    day1, day2 = tx[tx["day"] == 1], tx[tx["day"] == 2]
    scorer = train(day1)
    msgs = delivery(tx)
    proc = Processor(scorer)
    indexed = tx.set_index("txn_id")
    for start in range(0, len(msgs), BATCH):
        proc.process(msgs.iloc[start:start + BATCH], indexed)
    proc.close()

    alerts = pd.DataFrame(proc.alerts)
    windows = pd.DataFrame(proc.final_windows)
    model_ids = set(alerts.loc[alerts["model_alert"], "txn_id"])
    rule_ids = set(alerts.loc[alerts["rule_alert"], "txn_id"])
    late = msgs.loc[~msgs["is_redelivery"] & (msgs["arrival_seconds"] - msgs["event_seconds"] > 300), "txn_id"]
    late_tx = tx[tx["txn_id"].isin(late)]
    late_fraud = int(late_tx["is_fraud"].sum())
    late_fraud_alerted = int(late_tx.loc[late_tx["is_fraud"], "txn_id"].isin(model_ids | rule_ids).sum())
    alerts["delay_seconds"] = alerts["arrival_seconds"] - alerts["event_seconds"]
    late_alerts = int((alerts["delay_seconds"] > 300).sum())

    day1_scores = scorer.score(day1)
    day2_scores = scorer.score(day2)
    bins = np.quantile(day1_scores, np.linspace(0, 1, 11))
    bins[0], bins[-1] = -np.inf, np.inf
    p = np.histogram(day1_scores, bins)[0] / len(day1_scores)
    q = np.histogram(day2_scores, bins)[0] / len(day2_scores)
    psi = float(np.sum((q - p) * np.log(np.maximum(q, 1e-6) / np.maximum(p, 1e-6))))

    summary = {
        "transactions": len(tx), "frauds": int(tx["is_fraud"].sum()),
        "day1": {"transactions": len(day1), "frauds": int(day1["is_fraud"].sum())},
        "day2": {"transactions": len(day2), "frauds": int(day2["is_fraud"].sum())},
        "alert_budget": ALERT_BUDGET, "model_threshold": round(scorer.threshold, 5),
        "rules": {f: round(t, 3) for f, t in scorer.rules.items()},
        "delivery": {k: int(v) for k, v in proc.stats.items()},
        "late_messages_over_5_min": int(len(late)),
        "late_frauds": late_fraud, "late_frauds_still_alerted": late_fraud_alerted,
        "alerts_on_late_events": late_alerts,
        "windows_finalised": len(windows),
        "batch_ms_p50": round(float(np.percentile(proc.batch_ms, 50)), 2),
        "batch_ms_p99": round(float(np.percentile(proc.batch_ms, 99)), 2),
        "per_event_ms_p50": round(float(np.percentile(proc.batch_ms, 50)) / BATCH, 4),
        "score_psi_day1_vs_day2": round(psi, 4),
        "day2_rules_only": evaluate(day2, rule_ids),
        "day2_model_only": evaluate(day2, model_ids),
        "day2_rules_or_model": evaluate(day2, rule_ids | model_ids),
    }
    (args.out / "run_summary.json").write_text(json.dumps(summary, indent=2))
    con = duckdb.connect(str(args.out / "stream.duckdb"))
    for name, frame in (("alerts", alerts), ("windows", windows)):
        con.register("df", frame)
        con.execute(f"create or replace table {name} as select * from df")
        con.unregister("df")
    con.close()

    hourly = windows.assign(hour=(windows["window_start"] // 3600).astype(int)).groupby("hour")[["transactions", "alerts"]].sum()
    lines = ["# Run summary", "", "Generated by `python -m stream.simulate`. Day 1 trains; day 2 is the out-of-time test.", "",
             "| | Alerts | Frauds caught | Precision | Recall | Fraud amount caught |", "|---|---:|---:|---:|---:|---:|"]
    for label, key in (("Rules only", "day2_rules_only"), ("Model only", "day2_model_only"), ("Rules or model", "day2_rules_or_model")):
        e = summary[key]
        lines.append(f"| {label} | {e['alerts']:,} | {e['frauds_caught']} of {e['frauds']} | {e['precision']:.1%} | "
                     f"{e['recall']:.1%} | {e['fraud_value_caught']:,.0f} of {e['fraud_value']:,.0f} |")
    d = summary["delivery"]
    lines += ["", f"Messages {d['messages']:,}; redeliveries ignored {d['redeliveries_ignored']:,}; transactions processed "
              f"{d['processed']:,}; late events kept out of finalised windows {d['late_events']:,}.",
              f"Events arriving over 5 minutes late: {len(late):,}, all still scored; {late_alerts} raised alerts. Late frauds (both days): {late_fraud}, still alerted: {late_fraud_alerted}.",
              f"Batch of {BATCH}: p50 {summary['batch_ms_p50']} ms, p99 {summary['batch_ms_p99']} ms. Score PSI day 1 vs day 2: {summary['score_psi_day1_vs_day2']}.",
              "", "Transactions and alerts by hour (event time):", "", "| Hour | Transactions | Alerts |", "|---:|---:|---:|"]
    lines += [f"| {h} | {int(r.transactions):,} | {int(r.alerts)} |" for h, r in hourly.iterrows()]
    (args.out / "run_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
